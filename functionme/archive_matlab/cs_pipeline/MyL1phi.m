function y=MyL1phi(x)
% MyL1phi - L1 正则项接口函数 Phi(x)
%
% 【用途】
%   计算 L1 正则项的值：Φ(x) = ||x||_1 = Σ |x_i|
%   作为 TV 正则的备选方案，用于 TwIST 优化器的停止准则判断。
%   当前默认使用 TV 正则（MyTVphi），此函数提供 L1 选项。
%
% 【在TV正则化链路中的位置】
%   被 TwIST 优化器直接调用，作为 Phi 接口（L1版本）。
%   与 MyTVphi 互为替代：
%     - MyTVphi：TV正则，利用图像的空间结构先验，适合分段常数信号
%     - MyL1phi：L1正则，直接对系数幅值惩罚，适合稀疏基下的表示
%
% 【数学含义】
%   L1 范数：Φ(x) = Σ_i √(Re(x_i)² + Im(x_i)²) = Σ_i |x_i|
%   对复数信号取模后求和，实现复数域的 L1 正则化。
%   L1 范数是 L0 范数（稀疏度）的最佳凸松弛。
%
% 【输入】
%   x - 列向量 (N, 1)，信号系数（可为复数）
%
% 【输出】
%   y - 标量，L1 正则项值 ||x||_1

% MyV2C：将向量转换为复数格式（若已是复数则不变，实数则虚部置零）
X=MyV2C(x(:));

% 计算每个元素的模（幅值），然后求和
% √(Re² + Im²) 即为复数的绝对值 |x_i|
y=sum(sqrt(real(X).^2+imag(X).^2));
