function [y,dif]=MyTVnorm(x)
% MyTVnorm - 三维全变分（TV）范数
%
% 【用途】
%   计算三维图像 x 的各向同性 TV 范数（TV L2 范数）：
%     TV(x) = Σ_{i,j,k} √( (∂x/∂i)² + (∂x/∂j)² + (∂x/∂k)² )
%
% 【在TV正则化链路中的位置】
%   MyTVphi → MyTVnorm → MyTV3D_conv
%   （被 MyTVphi 调用，计算正则项值，用于 TwIST 停止准则判断）
%
% 【数学含义】
%   TV 范数是图像梯度的 L1 范数（对梯度幅值求和），等价于：
%     Φ(x) = ||∇x||_{1,2} = Σ ||(∇x)_{i,j,k}||_2
%   其中 ||·||_2 是三个方向差分的欧几里得范数。
%   各向同性 TV（L2分组）比分段线性 TV（L1分组）旋转不变性更好。
%
% 【输入】
%   x - 三维数组 (nx, ny, nz)，待计算TV范数的图像
%
% 【输出】
%   y   - 标量，TV 范数总和 Σ ||∇x||_2
%   dif - 三维数组 (nx, ny, nz)，每个体素的梯度幅值 ||∇x_{i,j,k}||_2

% 计算三维前向差分（梯度），TV(:,:,:,d) 为第d方向的差分
TV=MyTV3D_conv(x);

% 沿第4维（方向维）求L2范数：dif_{i,j,k} = √(dx² + dy² + dz²)
% 即每个体素处三个方向差分的欧几里得范数
dif=sqrt(sum(TV.^2,4));

% 对所有体素的梯度幅值求和，得到总TV范数
y=sum(dif(:));
