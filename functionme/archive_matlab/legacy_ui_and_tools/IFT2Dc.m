%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% 二维中心化逆傅里叶变换 (2D Centered Inverse Fourier Transform)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% 【用途】
%   对二维频谱矩阵执行中心化逆傅里叶变换，从中心化频谱恢复空间域信号。
%   是 FT2Dc 的逆操作，用于全息重建中从频域传播结果恢复空域光场。
%
% 【数学公式】
%   中心化逆变换的移位因子符号取反：
%     g(m,n) = (-1)^(m+n) · IFFT{ (-1)^(m+n) · G(u,v) }
%   其中 (-1)^(m+n) = exp(-jπ(m+n))，与正变换互为逆运算。
%
% 【输入】
%   in  - 二维矩阵 (Nx × Ny)，中心化频谱，复数
%
% 【输出】
%   out - 二维矩阵 (Nx × Ny)，空间域复振幅
%
% 【参考文献】
%   Tatiana Latychevskaia and Hans-Werner Fink
%   "Practical algorithms for simulation and reconstruction of digital in-line holograms",
%   Appl. Optics 54, 2424-2434 (2015)
%
% 【作者】Tatiana Latychevskaia, 2002 (MATLAB R2010b)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

function [out] = IFT2Dc(in)

% 获取输入矩阵的行列数
[Nx, Ny] = size(in);

% 构造行索引列向量 ii (Nx×1) 和列索引行向量 jj (1×Ny)
ii = cast((1:Nx)', 'like', in);
jj = cast(1:Ny, 'like', in);

% 中心化逆移位因子 f1 = exp(-jπ(m+n)) = (-1)^(m+n)
% 注意：逆变换的指数符号为负，与正变换相反
f1 = exp(-1i * pi * (ii + jj));

% 步骤1: 输入频谱乘以移位因子
% 步骤2: 执行标准二维逆FFT
FT = ifft2(f1.*in);

% 步骤3: 输出再乘以移位因子，完成空间域的中心化对齐
out = f1.*FT;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
