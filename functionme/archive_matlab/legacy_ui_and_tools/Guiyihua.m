%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% [0,1] 归一化 (Normalization to [0,1])
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% 【用途】
%   将输入矩阵的值线性映射到 [0, 1] 区间。常用于图像显示前的归一化，
%   或将数值范围统一到标准区间以便后续处理。
%
% 【数学公式】
%   y = (x - xmin) / (xmax - xmin)
%   其中 xmin = min(x(:))，xmax = max(x(:))
%
% 【输入】
%   x - 任意维度的数值矩阵
%
% 【输出】
%   y - 与 x 同维度的矩阵，值域为 [0, 1]
%       当 xmax == xmin 时，结果为 NaN（全零输入的特殊情况）
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

function y = Guiyihua(x)

% 求输入矩阵的全局最大值
xmax = max(x(:));

% 求输入矩阵的全局最小值
xmin = min(x(:));

% 线性映射至 [0, 1]
y = (x-xmin)/(xmax-xmin);
end
