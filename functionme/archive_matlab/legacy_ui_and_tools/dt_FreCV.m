%{
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
卷积型菲涅尔变换 (Convolution Fresnel Transform)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
【用途】
  基于菲涅尔近似的自由空间传播，采用卷积形式实现。
  菲涅尔近似假设傍轴条件成立（传播距离 z 远大于物体尺寸），
  此卷积形式保持输入输出的采样间隔不变，适合近距离传播。

【数学公式】
  菲涅尔衍射的卷积表达：
    U_z(x,y) = U₀(x,y) ⊗ h(x,y)
  其中菲涅尔脉冲响应（点扩展函数）：
    h(x,y) = (1/(jλz)) · exp(jπ(x²+y²)/(λz))
  其傅里叶变换（传递函数）：
    H(fx,fy) = exp(jkz) · exp(jπλz(fx²+fy²))

  通过频域相乘实现卷积：
    U_z = IFT{ FT{U₀} · H }

  输出采样间隔与输入相同：du = dx, dv = dy

【输入】
  U0    - 输入复振幅光场 (Ny × Nx)
  dx    - x 方向像素间距 (m)
  dy    - y 方向像素间距 (m)
  z     - 传播距离 (m)
  lambda- 波长 (m)

【输出】
  Uz    - 传播后的复振幅光场 (Ny × Nx)
  du    - 输出 x 方向采样间距 (m)，等于 dx
  dv    - 输出 y 方向采样间距 (m)，等于 dy

【备注】
  此方法适用于近距传播。远距离传播应使用傅里叶型菲涅尔变换，
  因其采样间隔随距离变化，更适合远场。

【作者】Neysa, 2009/12/29, 更新于 2016/11/04
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%}
function [Uz, du, dv] = dt_FreCV(U0, dx, dy, z, lambda)
    % 定义中心化FFT和逆FFT
    FT = @(x) ifftshift(fft2(fftshift(x)));
    iFT = @(x) ifftshift(ifft2(fftshift(x)));
    
    % 波数 k = 2π/λ
    k = 2*pi/lambda;

    % 获取输入场尺寸
    [Ny, Nx] = size(U0); 

    % 构造以零为中心的空间坐标
    % round(N/2) 为中心像素索引，偏移后坐标范围约为 [-N/2, N/2-1]
    xc = ((1:Nx)-round(Nx/2))*dx;
    yc = ((1:Ny)-round(Ny/2))*dy;
    [x, y] = meshgrid(xc, yc);
    
    % 计算计算窗口的物理尺寸
    Lx = dx*Nx;
    Ly = dy*Ny;

    % 对输入光场做中心化FFT，得到频谱
    % 注：乘以 dx*dy 的版本为物理量纲正确的傅里叶变换，
    %     此处未乘，后续在 H 中统一处理
    U0_prime = FT(U0);
    
    % 计算频率域采样间隔
    dfx = 1/Lx;
    dfy = 1/Ly;
        
    % 构造以零为中心的频率坐标
    fu = ((1:Nx)-round(Nx/2))*dfx;
    fv = ((1:Ny)-round(Ny/2))*dfy;
    [u, v] = meshgrid(fu, fv); 

    % 菲涅尔脉冲响应 h(x,y) = (1/(jλz)) · exp(jπ(x²+y²)/(λz))
    h = 1/(1i*lambda*z)*exp(1i*pi/lambda/z.*(x.^2+y.^2));

    % 对 h 做中心化FFT并乘以 dx*dy 得到传递函数 H
    % 乘以 dx*dy 是离散傅里叶变换与连续傅里叶变换之间的尺度修正
    H = FT(h)*dx*dy;
    
    % 频域相乘后逆变换，得到传播后的光场
    Uz = iFT(U0_prime.*H);

    % 卷积型菲涅尔变换的输出采样间隔与输入相同
    du = dx;
    dv = dy; 
end
